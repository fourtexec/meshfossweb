let current = 'ru';

export function setLang(code) {
  current = DICT[code] ? code : 'ru';
  if (typeof document !== 'undefined') document.documentElement.lang = current;
}

export const lang = () => current;

/** Перевод по ключу; `%s` заменяются аргументами по порядку. */
export function t(key, ...args) {
  const template = DICT[current]?.[key] ?? DICT.ru[key] ?? key;
  let i = 0;
  return template.replace(/%s/g, () => String(args[i++] ?? ''));
}

export function detectLang() {
  const nav = (typeof navigator !== 'undefined' && navigator.language || 'ru').slice(0, 2);
  return DICT[nav] ? nav : 'ru';
}
